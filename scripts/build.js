// Writes the cards' bundle, the one file the integration serves, from the
// card scripts in src/cards/.
//
//   node scripts/build.js          write the bundle
//   node scripts/build.js --check  exit 1 if the bundle is out of date
//
// The scripts go, in the order of SOURCES, into one block, so they share its
// scope as if they were one file: each can use what the others declare, and
// no two can declare the same name. The bundle loads as a module, so it is
// strict code, and nothing it declares reaches the page's global scope.

const fs = require("node:fs");
const path = require("node:path");

// In the order they run. What runs as the bundle loads, such as a class's
// `extends` and static fields or a constant's value, can only use names
// declared above it, in its own script or an earlier one. The cards' methods
// run later, once every script has, and can use any name.
const SOURCES = [
  "cards/header.js",
  "cards/strings.js",
  "cards/strings/en.js",
  "cards/strings/de.js",
  "cards/strings/es.js",
  "cards/strings/fr.js",
  "cards/strings/it.js",
  "cards/strings/nl.js",
  "cards/strings/pl.js",
  "cards/strings/pt.js",
  "cards/strings/pt-BR.js",
  "cards/strings/sv.js",
  "cards/strings/zh-Hans.js",
  "cards/helpers.js",
  "cards/food-form.js",
  "cards/meals.js",
  "cards/fitness-card.js",
  "cards/food-card.js",
  "cards/editor.js",
  "cards/person-card.js",
  "cards/food-diary-card.js",
  "cards/foods-card.js",
  "cards/meals-card.js",
  "cards/charts.js",
  "cards/weights.js",
  "cards/weight-card.js",
  "cards/trends-card.js",
  "cards/summary-card.js",
  "cards/register.js",
];
const root = path.join(__dirname, "..");
const sources = SOURCES.map((name) => path.join(root, "src", name));
const out = path.join(root, "custom_components", "fork_and_scale", "frontend", "fork-and-scale-cards.js");

function build() {
  const parts = SOURCES.map((name) => {
    const code = fs.readFileSync(path.join(root, "src", name), "utf8").trimEnd();
    return `// src/${name}\n${code}\n`;
  });
  return "// Fork & Scale: generated by scripts/build.js from src/. Edit src/, not this file.\n\n{\n" + parts.join("\n") + "}\n";
}

if (require.main === module) {
  const bundle = build();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== bundle) {
      console.error(`${path.relative(root, out)} is out of date: run node scripts/build.js`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, bundle);
  }
}

module.exports = { build, out, sources };
