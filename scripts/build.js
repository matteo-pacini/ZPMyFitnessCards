// Writes the cards' bundle, the one file the integration serves, from the
// card scripts in src/.
//
//   node scripts/build.js          write the bundle
//   node scripts/build.js --check  exit 1 if the bundle is out of date
//
// Each script goes in its own block, so scripts can declare the same top-level
// names (esc, STRINGS, ...) without clashing. That holds because the bundle
// loads as a module, so it is strict code and function declarations stay
// inside their block.

const fs = require("node:fs");
const path = require("node:path");

const SOURCES = ["food-diary-card.js"];
const root = path.join(__dirname, "..");
const out = path.join(root, "custom_components", "zp_my_fitness", "frontend", "zp-my-fitness-cards.js");

function build() {
  const parts = SOURCES.map((name) => {
    const code = fs.readFileSync(path.join(root, "src", name), "utf8").trimEnd();
    return `// src/${name}\n{\n${code}\n}\n`;
  });
  return "// ZPMyFitnessCards: generated by scripts/build.js from src/. Edit src/, not this file.\n\n" + parts.join("\n");
}

if (require.main === module) {
  const bundle = build();
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(out) || fs.readFileSync(out, "utf8") !== bundle) {
      console.error(`${path.relative(root, out)} is out of date: run node scripts/build.js`);
      process.exit(1);
    }
  } else {
    fs.writeFileSync(out, bundle);
  }
}

module.exports = { build, out };
